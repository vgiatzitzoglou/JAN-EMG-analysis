function yield = collectParticipantYield(output_base,subjects,sil_thresholds)
% Collect the current run's five-cutoff summaries for the selected subjects.
parts = cell(numel(subjects),1);
for s = 1:numel(subjects)
    filename = fullfile(output_base,"participant_"+subjects(s), ...
        'sil_comparison','sil_tracking_summary.csv');
    current = sortrows(readResultsTable(filename),'sil_threshold');
    assert(height(current)==numel(sil_thresholds) && ...
        isequal(current.sil_threshold,sort(sil_thresholds(:))) && ...
        all(current.participant==subjects(s)), ...
        'Participant %s does not have the complete SIL summary.',subjects(s));
    assert(all(current.usable_trials>0) && ...
        numel(unique(current.usable_trials))==1 && ...
        numel(unique(current.exported_input_detections))==1 && ...
        all(current.accepted_detections>=0 & ...
        current.accepted_detections<=current.exported_input_detections), ...
        'Trial denominators or detection counts are inconsistent for %s.',subjects(s));
    current.prepared_per_usable_trial = ...
        current.exported_input_detections./current.usable_trials;
    current.accepted_per_usable_trial = ...
        current.accepted_detections./current.usable_trials;
    parts{s} = current(:,{'participant','sil_threshold','usable_trials', ...
        'exported_input_detections','accepted_detections', ...
        'prepared_per_usable_trial','accepted_per_usable_trial'});
end
yield = vertcat(parts{:});
end
