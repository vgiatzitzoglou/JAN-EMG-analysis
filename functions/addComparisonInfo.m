function [candidates,comparison_id] = addComparisonInfo(candidates, ...
    subj,condition_a,condition_b,A,B)
% Add trial and condition identifiers to every MU-pair score.
comparison_id = "P" + subj + "_" + condition_a.label + "_trial" ...
    + compose('%02d',A.rep) + "_vs_" + condition_b.label + "_trial" ...
    + compose('%02d',B.rep);
n = height(candidates);
information = table(repmat(comparison_id,n,1),repmat(subj,n,1), ...
    repmat(condition_a.label,n,1),repmat(condition_b.label,n,1), ...
    repmat(condition_a.digit,n,1),repmat(condition_b.digit,n,1), ...
    repmat(condition_a.force_label,n,1), ...
    repmat(condition_b.force_label,n,1), ...
    repmat(condition_a.profile,n,1),repmat(condition_b.profile,n,1), ...
    repmat(A.rep,n,1),repmat(B.rep,n,1), ...
    repmat(A.file,n,1),repmat(B.file,n,1), ...
    'VariableNames',{'comparison_id','participant','condition_a', ...
    'condition_b','digit_a','digit_b','force_a','force_b', ...
    'profile_a','profile_b','rep_a','rep_b','file_a','file_b'});

candidates = [information,candidates];
end
