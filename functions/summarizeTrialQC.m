function summary = summarizeTrialQC(units)
% Count accepted and rejected MUs within every trial.
files = unique(units.file,'stable');
summary = table();

for file = files'
    rows = units(units.file == file,:);
    new_row = table(rows.participant(1),rows.digit(1), ...
        rows.force_label(1),rows.force(1),rows.profile(1),rows.rep(1), ...
        file,height(rows),sum(rows.valid_after_qc), ...
        sum(~rows.valid_after_qc), ...
        sum(rows.qc_reason == "fewer than 30 spikes"), ...
        sum(rows.passes_spike_count & ~rows.passes_sil), ...
        sum(rows.qc_reason == "CoV not below 30 percent"), ...
        sum(rows.qc_reason == "no active period"), ...
        sum(rows.qc_reason == "recruited too late"), ...
        'VariableNames',{'participant','digit','force_label','force', ...
        'profile','rep','file','total_mu','accepted_mu','rejected_mu', ...
        'rejected_few_spikes','rejected_low_sil','rejected_high_cov', ...
        'rejected_no_active_period', ...
        'rejected_late_recruitment'});

    summary = [summary;new_row];
end
end
