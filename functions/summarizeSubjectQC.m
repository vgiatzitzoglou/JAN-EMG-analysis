function summary = summarizeSubjectQC(units)
% Count accepted and rejected MUs for each participant.
subjects = unique(units.participant,'stable');
summary = table();

for subj = subjects'
    rows = units(units.participant == subj,:);
    new_row = table(subj,numel(unique(rows.file)),height(rows), ...
        sum(rows.valid_after_qc),sum(~rows.valid_after_qc), ...
        sum(rows.qc_reason == "fewer than 30 spikes"), ...
        sum(rows.passes_spike_count & ~rows.passes_sil), ...
        sum(rows.qc_reason == "CoV not below 30 percent"), ...
        sum(rows.qc_reason == "no active period"), ...
        sum(rows.qc_reason == "recruited too late"), ...
        'VariableNames',{'participant','trials_checked','total_mu', ...
        'accepted_mu','rejected_mu','rejected_few_spikes', ...
        'rejected_low_sil','rejected_high_cov', ...
        'rejected_no_active_period','rejected_late_recruitment'});

    summary = [summary;new_row];
end
end
